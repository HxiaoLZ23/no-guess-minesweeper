  NG.I18N = { en: en, zh: zh };
  NG.lang = "en";

  function langMeta(id) {
    for (var i = 0; i < NG.LANGS.length; i++) if (NG.LANGS[i].id === id) return NG.LANGS[i];
    return NG.LANGS[0];
  }

  function lookup(lang, key) {
    var order = [lang, "en"];
    if (lang === "zh-Hant") order = ["zh-Hant", "en"];
    for (var i = 0; i < order.length; i++) {
      var pack = NG.I18N[order[i]];
      if (pack && pack[key] != null && pack[key] !== "") return pack[key];
    }
    return null;
  }

  NG.t = function (key, vars) {
    var s = lookup(NG.lang, key);
    if (s == null) return key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split("{" + k + "}").join(vars[k] == null ? "" : String(vars[k]));
      });
    }
    return s;
  };

  NG.lessonField = function (ls, field) {
    if (!ls) return "";
    var s = NG.t("ls." + ls.id + "." + field);
    if (s && s.indexOf("ls.") !== 0) return s;
    return ls[field] || "";
  };

  NG.chapterName = function (key) {
    var s = NG.t("ch." + key);
    return s.indexOf("ch.") === 0 ? key : s;
  };

  NG.diffName = function (id) {
    var s = NG.t("diff." + id);
    return s.indexOf("diff.") === 0 ? id : s;
  };

  NG.applyDom = function (root) {
    var scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = NG.t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.title = NG.t(el.getAttribute("data-i18n-title"));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", NG.t(el.getAttribute("data-i18n-aria")));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.placeholder = NG.t(el.getAttribute("data-i18n-placeholder"));
    });
  };

  NG.setLang = function (id, silent) {
    var meta = langMeta(id);
    if (!meta) { id = "en"; meta = langMeta("en"); }
    NG.lang = meta.id;
    document.documentElement.lang = meta.html;
    document.documentElement.dir = meta.dir || "ltr";
    document.title = NG.t("app.title");
    NG.applyDom(document);
    if (!silent && typeof NG.onLang === "function") NG.onLang();
  };

  NG.fillLangSelect = function (sel, current) {
    if (!sel) return;
    var v = current || NG.lang;
    sel.innerHTML = "";
    NG.LANGS.forEach(function (item) {
      var o = document.createElement("option");
      o.value = item.id;
      o.textContent = item.name;
      sel.appendChild(o);
    });
    sel.value = v;
  };
