function stage(cols, rows, startC, startR, mines) {
  var side = Math.max(cols, rows);
  var chapter = side <= 10 ? "beginner" : side <= 14 ? "intermediate" : "expert";
  var cell = NG.cellFor(rows, cols);
  return {
    id: "s" + cols + "x" + rows,
    chapter: chapter,
    title: cols + "×" + rows,
    text: cols + "×" + rows + "，" + mines.length + " 颗雷。",
    rows: rows,
    cols: cols,
    startR: startR,
    startC: startC,
    cell: cell,
    mines: mines,
  };
}
